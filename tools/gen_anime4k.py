#!/usr/bin/env python3
"""Convert Anime4K mpv user shaders into Vulkan compute shaders for Lyvra.

Each mpv "pass" (//!DESC ... //!HOOK ... //!BIND ... //!SAVE ... //!WIDTH ... hook())
becomes one compute shader: every bound texture is a combined image sampler,
the output is a storage image, and mpv's per-texture helpers (NAME_tex, NAME_texOff,
NAME_pos, NAME_pt, NAME_size) are provided as macros. Texture sizes come from push
constants; the WIDTH/HEIGHT expressions (mpv's RPN) are evaluated at runtime.

Usage: gen_anime4k.py --glslc GLSLC --out anime4k_passes.h NAME=shader.glsl [...]
"""
import argparse
import os
import re
import struct
import subprocess
import sys
import tempfile

MAX_BINDS = 8


def parse(path):
    passes, cur, body = [], None, []
    for line in open(path, encoding="utf-8"):
        m = re.match(r"^//!(\w+)\s*(.*?)\s*$", line)
        if m and m.group(1) == "DESC":
            if cur:
                cur["body"] = "".join(body)
                passes.append(cur)
            cur, body = {"desc": m.group(2), "binds": [], "save": None, "width": None, "height": None, "hook": "MAIN"}, []
        elif m and cur is not None:
            key, val = m.group(1), m.group(2)
            if key == "BIND":
                cur["binds"].append(val)
            elif key == "SAVE":
                cur["save"] = val
            elif key == "WIDTH":
                cur["width"] = val
            elif key == "HEIGHT":
                cur["height"] = val
            elif key == "HOOK":
                cur["hook"] = val
            # COMPONENTS / WHEN are ignored: Lyvra always uses RGBA and decides when to run.
        elif cur is not None:
            body.append(line)
    if cur:
        cur["body"] = "".join(body)
        passes.append(cur)
    for p in passes:
        p["save"] = p["save"] or p["hook"]
        p["final"] = p["save"] == "MAIN"
        p["width"] = p["width"] or (p["binds"][0] + ".w")
        p["height"] = p["height"] or (p["binds"][0] + ".h")
        if len(p["binds"]) > MAX_BINDS:
            sys.exit(f"{path}: pass '{p['desc']}' binds {len(p['binds'])} textures (max {MAX_BINDS})")
    return passes


def glsl_for(p):
    out = ["#version 450", "layout(local_size_x = 8, local_size_y = 8) in;",
           f"layout(push_constant) uniform PC {{ vec2 outSize; vec2 sizes[{MAX_BINDS}]; }} pc;"]
    for i, name in enumerate(p["binds"]):
        out.append(f"layout(binding = {i}) uniform sampler2D t{i};")
    fmt = "rgba8" if p["final"] else "rgba16f"
    out.append(f"layout({fmt}, binding = {len(p['binds'])}) writeonly uniform image2D outImg;")
    out.append("#define LYVRA_POS ((vec2(gl_GlobalInvocationID.xy) + 0.5) / pc.outSize)")
    for i, name in enumerate(p["binds"]):
        aliases = [name] + (["HOOKED"] if name == p["hook"] else [])
        for a in aliases:
            out += [f"#define {a}_size (pc.sizes[{i}])",
                    f"#define {a}_pt (1.0 / pc.sizes[{i}])",
                    f"#define {a}_pos LYVRA_POS",
                    f"#define {a}_mul 1.0",
                    f"#define {a}_tex(p) texture(t{i}, (p))",
                    f"#define {a}_texOff(o) texture(t{i}, LYVRA_POS + (1.0 / pc.sizes[{i}]) * (o))"]
    out.append(p["body"])
    out.append("void main() {\n"
               "    if (any(greaterThanEqual(vec2(gl_GlobalInvocationID.xy), pc.outSize))) return;\n"
               "    imageStore(outImg, ivec2(gl_GlobalInvocationID.xy), hook());\n}")
    return "\n".join(out) + "\n"


def compile_spv(glslc, src):
    with tempfile.TemporaryDirectory() as d:
        s, o = os.path.join(d, "pass.comp"), os.path.join(d, "pass.spv")
        open(s, "w").write(src)
        r = subprocess.run([glslc, "-O", "--target-env=vulkan1.3", "-fshader-stage=comp", s, "-o", o],
                           capture_output=True, text=True)
        if r.returncode != 0:
            sys.exit("glslc failed:\n" + r.stderr + "\n--- source ---\n" + src)
        data = open(o, "rb").read()
    return struct.unpack(f"<{len(data) // 4}I", data)


def c_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--glslc", required=True)
    ap.add_argument("--out", required=True)
    ap.add_argument("variants", nargs="+", help="NAME=path/to/shader.glsl")
    a = ap.parse_args()

    lines = ["// Generated by tools/gen_anime4k.py from Anime4K (MIT). Do not edit.", "#pragma once",
             "#include <cstdint>", "",
             "struct Anime4KPassDesc {", "    const uint32_t* spv;", "    uint32_t spvBytes;", "    uint32_t numBinds;",
             f"    const char* binds[{MAX_BINDS}];", "    const char* save;", "    const char* width;   // mpv RPN",
             "    const char* height;  // mpv RPN", "    bool final;          // writes the RGBA8 result", "};", "",
             "struct Anime4KVariant { const char* name; const Anime4KPassDesc* passes; uint32_t count; };", ""]
    table = []
    for spec in a.variants:
        name, path = spec.split("=", 1)
        passes = parse(path)
        descs = []
        for i, p in enumerate(passes):
            words = compile_spv(a.glslc, glsl_for(p))
            sym = f"kA4K_{name}_{i}"
            lines.append(f"// {p['desc']}")
            lines.append(f"static const uint32_t {sym}[] = {{" + ",".join(f"0x{w:08x}u" for w in words) + "};")
            binds = ", ".join(c_str(b) for b in p["binds"])
            descs.append(f"    {{{sym}, sizeof({sym}), {len(p['binds'])}u, {{{binds}}}, {c_str(p['save'])}, "
                         f"{c_str(p['width'])}, {c_str(p['height'])}, {'true' if p['final'] else 'false'}}},")
        lines.append(f"static const Anime4KPassDesc kA4K_{name}[] = {{")
        lines += descs
        lines.append("};")
        table.append(f"    {{{c_str(name)}, kA4K_{name}, {len(passes)}u}},")
    lines.append("static const Anime4KVariant kAnime4KVariants[] = {")
    lines += table
    lines.append("};")
    open(a.out, "w").write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
